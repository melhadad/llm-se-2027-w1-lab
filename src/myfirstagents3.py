"""A small file-reading agent. Run with: uv run python -m myfirstagents3."""

from __future__ import annotations

import os
from pathlib import Path
import sys
from typing import cast

from dotenv import load_dotenv
from openai import APIConnectionError, APIStatusError, OpenAI
from openai.types.chat import (
    ChatCompletionAssistantMessageParam,
    ChatCompletionMessageParam,
    ChatCompletionToolParam,
)
from pydantic import BaseModel, ConfigDict, ValidationError

from triage.privacy import redact_secrets

ROOT = Path(__file__).resolve().parent.parent
FILE_ROOT = ROOT / "tools"
MAX_FILE_BYTES = 64 * 1024
DEFAULT_PROMPT = "What is the content of the file 'example.txt'?"


class ReadFileArguments(BaseModel):
    """Treat arguments generated by the model as untrusted input."""

    model_config = ConfigDict(extra="forbid", strict=True)
    path: str


def read_file(path: str) -> str:
    """Read a small UTF-8 .txt file inside tools/, independent of the terminal cwd."""
    try:
        allowed_root = FILE_ROOT.resolve()
        target = (allowed_root / path).resolve()
        if not target.is_relative_to(allowed_root) or target.suffix.lower() != ".txt":
            return "Error: only .txt files inside tools/ can be read."
        with target.open("rb") as stream:
            raw = stream.read(MAX_FILE_BYTES + 1)
        if len(raw) > MAX_FILE_BYTES:
            return "Error: file exceeds the 64 KiB limit."
        return redact_secrets(raw.decode("utf-8"))
    except FileNotFoundError:
        return "Error: file not found."
    except (OSError, UnicodeError, ValueError):
        return "Error: could not read the file as UTF-8 text."


TOOL_SCHEMA: list[ChatCompletionToolParam] = [{
    "type": "function",
    "function": {
        "name": "read_file",
        "description": "Read a UTF-8 .txt file inside tools/. Paths are relative to tools/.",
        "strict": True,
        "parameters": {
            "type": "object",
            "properties": {"path": {"type": "string"}},
            "required": ["path"],
            "additionalProperties": False,
        },
    },
}]


def execute_tool(name: str, arguments: str) -> str:
    if name != "read_file":
        return "Error: unknown tool."
    try:
        args = ReadFileArguments.model_validate_json(arguments)
    except ValidationError:
        return "Error: read_file requires exactly one string argument named path."
    return read_file(args.path)


def run_agent(client: OpenAI, prompt: str = DEFAULT_PROMPT, *, max_steps: int = 5) -> str:
    """Ask the model, execute requested tools, then return its final text."""
    messages: list[ChatCompletionMessageParam] = [
        {"role": "user", "content": redact_secrets(prompt)},
    ]
    for _ in range(max_steps):
        response = client.chat.completions.create(
            model="gpt-5-mini", messages=messages, tools=TOOL_SCHEMA,
        )
        if not response.choices:
            raise ValueError("The model returned no choices.")
        message = response.choices[0].message
        if not message.tool_calls:
            if not message.content:
                raise ValueError("The model returned no answer.")
            return redact_secrets(message.content)

        # Send the assistant's tool requests before their corresponding results.
        messages.append(cast(
            ChatCompletionAssistantMessageParam, message.model_dump(exclude_none=True),
        ))
        for tool_call in message.tool_calls:
            if tool_call.type != "function":
                raise ValueError("The model requested an unsupported tool type.")
            result = execute_tool(tool_call.function.name, tool_call.function.arguments)
            messages.append({
                "role": "tool",
                "tool_call_id": tool_call.id,
                "content": result,
            })
    raise RuntimeError("The agent reached its model-request limit without a final answer.")


def main() -> int:
    load_dotenv(ROOT / ".env")
    if not os.getenv("OPENAI_API_KEY"):
        print("Set OPENAI_API_KEY in the project .env file.", file=sys.stderr)
        return 2
    try:
        with OpenAI(timeout=30.0, max_retries=0) as client:
            answer = run_agent(client)
    except APIConnectionError:
        print("Could not connect to OpenAI; check network access.", file=sys.stderr)
        return 1
    except APIStatusError as exc:
        print(f"OpenAI returned HTTP {exc.status_code}; check credentials, access, and quota.",
              file=sys.stderr)
        return 1
    except (ValueError, RuntimeError):
        print("The agent could not produce an answer within its request limit.", file=sys.stderr)
        return 1
    print(answer)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
